function roomCode() { const chars='ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; let out=''; for(let i=0;i<6;i++) out+=chars[Math.floor(Math.random()*chars.length)]; return out; }
function makeSupabase() {
  if (!SUPABASE_URL || !SUPABASE_ANON_KEY || !window.supabase?.createClient) return null;
  try { return window.supabase.createClient(SUPABASE_URL, SUPABASE_ANON_KEY); } catch (error) { console.error('Supabase init failed', error); return null; }
}
function persistRoom(room) {
  const rooms = getRooms(); rooms[room.code] = room; setRooms(rooms);
  try { localStorage.setItem(STORAGE.lastRoom, room.code); } catch {}
  if (state.channel) state.channel.postMessage({ room });
  if (state.online && state.supabase) {
    state.supabase.from('dc_rooms').upsert({ code: room.code, data: room, updated_at: new Date().toISOString() }, { onConflict: 'code' }).then(({error}) => { if (error) console.error('Room sync failed', error); });
  }
}
function setupLocalChannel() {
  if (state.channel) state.channel.close();
  if ('BroadcastChannel' in window) {
    state.channel = new BroadcastChannel('deadlock-challenge-v1');
    state.channel.onmessage = event => { const room = event.data?.room; if (room?.code === state.room) { const all=getRooms(); all[room.code]=room; setRooms(all); renderRoom(room); } };
  }
}
function setupRealtime() {
  if (!state.online || !state.supabase || !state.room) return;
  if (state.realtime) state.supabase.removeChannel(state.realtime);
  state.realtime = state.supabase.channel(`dc-room-${state.room}`).on('postgres_changes', { event:'*', schema:'public', table:'dc_rooms', filter:`code=eq.${state.room}` }, payload => {
    const room = payload.new?.data; if (!room || room.code !== state.room) return;
    const all=getRooms(); all[room.code]=room; setRooms(all); renderRoom(room);
  }).subscribe();
}
