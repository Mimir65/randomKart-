function drawDuo() {
  const room=getRoom(); if(!room || state.player===null) return;
  const mine=room.players[state.player]; if(mine.pick || !room.players[1].name || room.players.some(p=>p.done)) return;
  const other=room.players[1-state.player].pick?.id;
  const card=randomCard([...mine.used, ...(other?[other]:[])]);
  mine.pick={id:card.id,title:card.title,description:card.description}; mine.used=[...mine.used,card.id];
  if(mine.used.length>=challengeDeck.length) mine.used=[];
  room.revealed=!!(room.players[0].pick&&room.players[1].pick); persistRoom(room); renderRoom(room);
  toast(room.revealed?'ОБЕ КАРТЫ ОТКРЫТЫ':'ВЫБОР ЗАФИКСИРОВАН — ЖДЁМ НАПАРНИКА');
}
function completeDuo() {
  const room=getRoom(); if(!room || !room.revealed) return;
  const mine=room.players[state.player]; if(!mine.pick || mine.done) return;
  mine.done=true;
  if(room.players.every(p=>p.done)) {
    room.round=(room.round||1)+1; room.players.forEach(p=>{p.pick=null;p.done=false;}); room.revealed=false;
    persistRoom(room); renderRoom(room); toast('ОБА ВЫПОЛНИЛИ — НАЧИНАЕТСЯ НОВЫЙ РАУНД');
  } else { persistRoom(room); renderRoom(room); toast('ПОДТВЕРЖДЕНО. ЖДЁМ ВТОРОГО ИГРОКА.'); }
}
