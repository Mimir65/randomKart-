function safeRead(key, fallback) { try { const value = JSON.parse(localStorage.getItem(key)); return value ?? fallback; } catch { return fallback; } }
function safeWrite(key, value) { try { localStorage.setItem(key, JSON.stringify(value)); } catch { toast('НЕ УДАЛОСЬ СОХРАНИТЬ ПРОГРЕСС В БРАУЗЕРЕ'); } }
