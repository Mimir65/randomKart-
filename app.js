function cardMarkup(card, indexLabel = '000') {
  return `<span class="draw-card-index">CARD / ${indexLabel}</span><strong>${escapeHTML(card.title)}</strong><small>${escapeHTML(card.description)}</small>`;
}
function escapeHTML(value) { return String(value).replace(/[&<>"']/g, ch => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[ch])); }
function randomCard(excluded = []) {
  const blocked = new Set(excluded);
  let pool = challengeDeck.filter(card => !blocked.has(card.id));
  if (!pool.length) pool = challengeDeck.slice();
  return pool[Math.floor(Math.random() * pool.length)];
}
function cardNumber(card) { return card.id.replace('DC-',''); }

